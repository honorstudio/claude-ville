// Remove only the authored detached tool, before palette/crest composition.
export function clearDetachedCodexWrench(ctx, width, height) {
    const cellSize = width / 8;
    const rows = Math.floor(height / cellSize);
    // GPT-5.4's only baked tool is a detached wrench above the right
    // shoulder. Keep its brass hands and armor intact.
    const starts = [[65], [58, 59, 59, 58, 58, 59, 61, 62, 57, 55], [59], [60], [64],
        [65, 66, 66, 66, 66, 66, 66, 64, 65, 65], [63, 62, 63, 63, 60, 62, 64, 62, 65, 64],
        [65, 65, 65, 65, 64, 65, 65, 65, 65, 65]];
    for (let row = 0; row < rows; row++) {
        for (let col = 0; col < 8; col++) {
            const startX = starts[col][row] ?? starts[col][0];
            ctx.clearRect(col * cellSize + startX * cellSize / 92, row * cellSize,
                (92 - startX) * cellSize / 92, (col === 2 ? 39 : col === 6 ? 35 : 34) * cellSize / 92);
        }
    }
}
